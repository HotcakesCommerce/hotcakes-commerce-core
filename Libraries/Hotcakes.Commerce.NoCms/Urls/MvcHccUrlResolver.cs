using System.Web.Mvc;
using System.Web.Routing;
using Hotcakes.Commerce.Accounts;
using Hotcakes.Commerce.Urls;

namespace Hotcakes.Commerce.NoCms.Urls
{
    /// <summary>
    /// Resolves HCC storefront routes and store URLs through ASP.NET MVC routing.
    /// </summary>
    /// <remarks>
    /// This internal adapter maps commerce routes to the named MVC routes registered by the host
    /// and uses the active store's custom URL when an absolute host is required.
    /// </remarks>
    internal class MvcHccUrlResolver : IHccUrlResolver
    {
        /// <summary>
        /// Resolves a commerce route into a URL using the supplied MVC routing context.
        /// </summary>
        /// <param name="route">The HCC destination to resolve.</param>
        /// <param name="actionName">The MVC action name, if applicable.</param>
        /// <param name="controllerName">The MVC controller name, if applicable.</param>
        /// <param name="protocol">The URL protocol, such as <c>http</c> or <c>https</c>.</param>
        /// <param name="hostName">The host name for an absolute URL; the current store host is used when empty.</param>
        /// <param name="fragment">The optional URL fragment.</param>
        /// <param name="routeValues">The values used to populate the selected route.</param>
        /// <param name="routeCollection">The MVC route collection used for URL generation.</param>
        /// <param name="requestContext">The current MVC request context.</param>
        /// <param name="includeImplicitMvcValues">Whether implicit MVC values should be included.</param>
        /// <returns>The URL generated by the selected named MVC route.</returns>
        /// <remarks>The adapter preserves the established route-name mapping and delegates URL generation to <see cref="UrlHelper.GenerateUrl(string, string, string, string, string, string, RouteValueDictionary, RouteCollection, RequestContext, bool)"/>.</remarks>
        public string RouteHccUrl(HccRoute route, string actionName, string controllerName, string protocol,
            string hostName, string fragment, RouteValueDictionary routeValues, RouteCollection routeCollection,
            RequestContext requestContext, bool includeImplicitMvcValues)
        {
            var routeName = GetRouteName(route);
            if (string.IsNullOrEmpty(hostName))
                hostName = GetHostName();
            return UrlHelper.GenerateUrl(routeName, null, null, protocol, hostName, null, routeValues, routeCollection,
                requestContext, false);
        }

        /// <summary>
        /// Gets the virtual path used to access data for a store.
        /// </summary>
        /// <param name="storeId">The identifier of the store.</param>
        /// <returns>The store data path under the MVC host's images directory.</returns>
        public string GetStoreDataVirtualPath(long storeId)
        {
            return string.Format("~/Images/sites/{0}/", storeId);
        }

        /// <summary>
        /// Gets the root URL for a store.
        /// </summary>
        /// <param name="store">The store whose custom URL supplies the host name.</param>
        /// <param name="secure">Whether to use HTTPS rather than HTTP.</param>
        /// <returns>The store root URL with a trailing slash.</returns>
        /// <remarks>The protocol is selected from <paramref name="secure"/> and the host is taken from <see cref="Store.CustomUrl"/>.</remarks>
        public string GetStoreRootUrl(Store store, bool secure)
        {
            var protocol = secure ? "https://" : "http://";
            return protocol + store.CustomUrl + "/";
        }

        private string GetRouteName(HccRoute route)
        {
            string routeName = null;
            switch (route)
            {
                case HccRoute.Product:
                case HccRoute.Category:
                    routeName = HccRouteNames.Custom;
                    break;
                case HccRoute.Cart:
                    routeName = HccRouteNames.Cart;
                    break;
                case HccRoute.ProductReview:
                    routeName = HccRouteNames.ProductReview;
                    break;
                case HccRoute.Checkout:
                    routeName = HccRouteNames.Checkout;
                    break;
                case HccRoute.CheckoutPayPal:
                    routeName = HccRouteNames.CheckoutPayPal;
                    break;
                case HccRoute.WishList:
                    routeName = HccRouteNames.WishList;
                    break;
                case HccRoute.Search:
                    routeName = HccRouteNames.Search;
                    break;
                case HccRoute.OrderHistory:
                case HccRoute.AddressBook:
                    routeName = HccRouteNames.AccountDefault;
                    break;
                case HccRoute.Login:
                    routeName = HccRouteNames.Login;
                    break;
                case HccRoute.Logoff:
                    routeName = HccRouteNames.Logoff;
                    break;
                case HccRoute.SendPassword:
                    routeName = HccRouteNames.SendPassword;
                    break;
                case HccRoute.Terms:
                    routeName = HccRouteNames.Terms;
                    break;
            }
            return routeName;
        }

        private string GetHostName()
        {
            return HccRequestContext.Current.CurrentStore.CustomUrl;
        }
    }
}
